#!/usr/bin/env python3
"""
Main orchestration script for SharePoint to Neo4j sync pipeline.

This script:
1. Runs sharepoint_new_site_pipeline.py to discover new sites and export document metadata
2. Collects all generated JSON files from the output directory
3. Runs ingest_to_neo4j.py to generate Cypher and execute against Neo4j
4. Provides a unified CLI for the entire sync process

Usage:
    python main.py                    # Full sync with default settings
    python main.py --dry-run          # Validate only, no Neo4j changes
    python main.py --output-dir ./custom_exports
    python main.py --skip-sharepoint  # Only run Neo4j ingestion on existing JSON files
"""

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any


# ──────────────────────────────────────────────────────────────────────────────
# CONFIGURATION
# ──────────────────────────────────────────────────────────────────────────────

BASE_DIR = Path(__file__).resolve().parent
PIPELINE_SCRIPT = BASE_DIR / "sharepoint_new_site_pipeline.py"
INGEST_SCRIPT = BASE_DIR / "ingest_to_neo4j.py"
DEFAULT_OUTPUT_DIR = BASE_DIR / "new_site_exports"

# Neo4j MCP tool names (for direct execution)
NEO4J_WRITE_CYPHER = "mcp__neo4j__write_cypher"
NEO4J_READ_CYPHER = "mcp__neo4j__read_cypher"


# ──────────────────────────────────────────────────────────────────────────────
# UTILITY FUNCTIONS
# ──────────────────────────────────────────────────────────────────────────────

def run_command(cmd: list[str], cwd: Path | None = None, capture: bool = True) -> subprocess.CompletedProcess:
    """Run a command and return the result."""
    print(f"  $ {' '.join(cmd)}")
    result = subprocess.run(
        cmd,
        cwd=cwd or BASE_DIR,
        capture_output=capture,
        text=True,
    )
    if result.stdout and capture:
        print(result.stdout)
    if result.stderr and capture:
        print(result.stderr, file=sys.stderr)
    return result


def find_json_files(output_dir: Path, recursive: bool = True) -> list[Path]:
    """Find all JSON files in the output directory or return the file if it's a JSON file."""
    if output_dir.is_file():
        if output_dir.suffix == ".json":
            return [output_dir]
        return []
    pattern = "**/*.json" if recursive else "*.json"
    return list(output_dir.glob(pattern))


def load_and_merge_json_files(json_files: list[Path]) -> list[dict]:
    """Load multiple JSON files and merge into a single document list."""
    all_documents = []
    for jf in json_files:
        print(f"  Loading {jf.name}...")
        with open(jf, "r", encoding="utf-8") as f:
            data = json.load(f)
        if isinstance(data, list):
            print(f"    ✓ {len(data)} document(s)")
            all_documents.extend(data)
        else:
            print(f"    ⚠ Skipping: not a JSON array")
    return all_documents


def generate_cypher_for_documents(documents: list[dict]) -> str:
    """Generate Cypher script for the given documents using the ingestion logic."""
    # Import the ingestion module's functions
    sys.path.insert(0, str(BASE_DIR))
    from ingest_to_neo4j import (
        build_ensure_hierarchy_cypher,
        build_document_upsert_cypher,
        build_cleanup_cypher,
        build_verification_cypher,
        infer_project_from_path,
        VALID_DOC_TYPES,
    )
    
    lines = [
        "// ═══════════════════════════════════════════════════════════════",
        "// Neo4j Document Ingestion Script (Auto-generated by main.py)",
        f"// Generated for {len(documents)} documents",
        "// ═══════════════════════════════════════════════════════════════",
        "",
        "// 1. Ensure Company, Tracks, Projects hierarchy exists",
        build_ensure_hierarchy_cypher().strip(),
        "",
        "// 2. Upsert documents (deduplication via sharepoint_url)",
    ]
    
    for doc in documents:
        department = doc.get("department", "HCM")
        track_var = f"t_{department.lower()}"
        
        project_name = infer_project_from_path(
            doc.get("sharepoint_path", ""), 
            doc.get("document_name", "")
        )
        project_var = None
        if project_name:
            safe_name = project_name.lower().replace(" ", "_").replace("-", "_").replace(".", "")
            project_var = f"p_{safe_name}"
        
        lines.append(build_document_upsert_cypher(doc, track_var, project_var).strip())
    
    lines.extend([
        "",
        "// 3. Clean up any duplicate relationships",
        build_cleanup_cypher().strip(),
        "",
        "// 4. Verification reports",
        build_verification_cypher().strip(),
    ])
    
    return "\n\n".join(lines)


