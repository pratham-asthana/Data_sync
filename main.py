def run_pipeline(output_dir: Path, skip_sharepoint: bool = False) -> list[Path]:
    """Run the SharePoint pipeline to generate JSON files."""
    if skip_sharepoint:
        print("\n⏭ Skipping SharePoint pipeline (--skip-sharepoint)")
        return find_json_files(output_dir)
    
    print("\n" + "=" * 60)
    print("STEP 1: Running SharePoint New Site Pipeline")
    print("=" * 60)
    
    cmd = [
        sys.executable,
        str(PIPELINE_SCRIPT),
        "--output-dir", str(output_dir),
    ]
    
    result = run_command(cmd)
    
    if result.returncode != 0:
        print(f"❌ Pipeline failed with exit code {result.returncode}")
        sys.exit(1)
    
    json_files = find_json_files(output_dir)
    print(f"\n📂 Found {len(json_files)} JSON file(s) in {output_dir}")
    return json_files


def run_ingestion(json_files: list[Path], dry_run: bool = False, execute_cypher: bool = False) -> bool:
    """Run the Neo4j ingestion on the JSON files."""
    print("\n" + "=" * 60)
    print("STEP 2: Neo4j Ingestion")
    print("=" * 60)
    
    if not json_files:
        print("❌ No JSON files to ingest")
        return False
    
    # Load all documents
    all_documents = load_and_merge_json_files(json_files)
    
    if not all_documents:
        print("❌ No valid documents found in JSON files")
        return False
    
    print(f"\n📄 Total documents to ingest: {len(all_documents)}")
    
    # Generate Cypher
    cypher = generate_cypher_for_documents(all_documents)
    
    if dry_run:
        print("\n✅ Dry run complete - Cypher generated but not executed")
        # Save to file for inspection
        cypher_path = BASE_DIR / "ingest_generated.cypher"
        cypher_path.write_text(cypher, encoding="utf-8")
        print(f"📝 Cypher saved to: {cypher_path}")
        return True
    
    # Execute via MCP (in Hermes environment)
    if execute_cypher:
        print("\n🚀 Executing Cypher via Neo4j MCP...")
        return execute_cypher_via_mcp(cypher)
    
    # Default: just generate and save Cypher
    cypher_path = BASE_DIR / "ingest_generated.cypher"
    cypher_path.write_text(cypher, encoding="utf-8")
    print(f"\n✅ Cypher script generated: {cypher_path}")
    print("   Execute via: mcp__neo4j__write_cypher tool, Neo4j Browser, or cypher-shell")
    return True


def print_summary(json_files: list[Path], all_documents: list[dict]):
    """Print a summary of the sync operation."""
    from collections import Counter
    
    type_counts = Counter(d.get("document_type", "UNKNOWN") for d in all_documents)
    dept_counts = Counter(d.get("department", "UNKNOWN") for d in all_documents)
    
    print("\n" + "=" * 60)
    print("SYNC SUMMARY")
    print("=" * 60)
    print(f"📁 JSON files processed: {len(json_files)}")
    print(f"📄 Total documents: {len(all_documents)}")
    
    print("\n📊 By document_type:")
    for t, c in sorted(type_counts.items()):
        print(f"    {t}: {c}")
    
    print("\n📊 By department:")
    for d, c in sorted(dept_counts.items()):
        print(f"    {d}: {c}")


# ──────────────────────────────────────────────────────────────────────────────
# MAIN ENTRY POINT
# ──────────────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(
        description="SharePoint to Neo4j Sync Pipeline Orchestrator",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python main.py                           # Full sync
  python main.py --dry-run                 # Validate only
  python main.py --skip-sharepoint         # Only ingest existing JSON
  python main.py --output-dir ./exports    # Custom output directory
  python main.py --execute-cypher          # Execute Cypher via MCP (Hermes)
        """
    )
    parser.add_argument(
        "--output-dir", "-o",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help=f"Directory for pipeline output (default: {DEFAULT_OUTPUT_DIR})"
    )
    parser.add_argument(
        "--skip-sharepoint", "-s",
        action="store_true",
        help="Skip SharePoint pipeline, only run Neo4j ingestion on existing JSON"
    )
    parser.add_argument(
        "--dry-run", "-n",
        action="store_true",
        help="Validate and generate Cypher but don't execute"
    )
    parser.add_argument(
        "--execute-cypher", "-e",
        action="store_true",
        help="Execute generated Cypher via Neo4j MCP (requires Hermes environment)"
    )
    parser.add_argument(
        "--recursive", "-r",
        action="store_true",
        help="Recursively search for JSON files in output directory"
    )
    
    args = parser.parse_args()
    
    print("🚀 SharePoint → Neo4j Sync Pipeline")
    print(f"   Output directory: {args.output_dir}")
    print(f"   Skip SharePoint: {args.skip_sharepoint}")
    print(f"   Dry run: {args.dry_run}")
    print(f"   Execute Cypher: {args.execute_cypher}")
    
    # Step 1: Run SharePoint pipeline
    json_files = run_pipeline(args.output_dir, args.skip_sharepoint)
    
    # Step 2: Run Neo4j ingestion
    if not json_files:
        print("\n⚠ No JSON files found. Exiting.")
        return
    
    # Load documents for summary
    all_documents = load_and_merge_json_files(json_files)
    
    success = run_ingestion(
        json_files,
        dry_run=args.dry_run,
        execute_cypher=args.execute_cypher
    )
    
    # Print summary
    print_summary(json_files, all_documents)
    
    if success:
        print("\n✅ Sync pipeline completed successfully!")
    else:
        print("\n❌ Sync pipeline failed!")
        sys.exit(1)


if __name__ == "__main__":
    main()